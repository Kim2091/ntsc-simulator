#!/usr/bin/env python3
"""Generate THIRD_PARTY_LICENSES.md from `cargo metadata`.

Lists every crate that can end up in a release build (all features, for the
Windows, Linux and macOS targets) with its licence expression, and appends the
licence/notice files shipped in each crate package.  Crates whose package has
no licence file get the text from licenses/overrides/<repo-key>/ if present.

Usage (from the repository root):
    python tools/third_party_licenses.py > THIRD_PARTY_LICENSES.md
"""

import json
import os
import subprocess
import sys

TARGETS = ["x86_64-pc-windows-msvc", "x86_64-unknown-linux-gnu", "aarch64-apple-darwin"]
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense", "copyright")
# Font licences bundled inside crate packages (e.g. egui's default fonts).
EXTRA_DIRS = ("fonts",)
OVERRIDES = os.path.join("licenses", "overrides")


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--all-features", "--filter-platform", target],
        check=True, capture_output=True,
    ).stdout
    return json.loads(out.decode("utf-8"))


def reachable(meta):
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen, stack = set(), [meta["resolve"]["root"]]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        stack.extend(d["pkg"] for d in nodes[i]["deps"])
    return seen


def licence_files(pkg, subdirs):
    root = os.path.dirname(pkg["manifest_path"])
    found = []
    for sub in subdirs:
        d = os.path.join(root, sub)
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            low = name.lower()
            path = os.path.join(d, name)
            is_font_txt = sub in EXTRA_DIRS and low.endswith(".txt")
            if os.path.isfile(path) and (low.startswith(LICENSE_PREFIXES) or is_font_txt):
                found.append(path)
    if "" in subdirs and pkg.get("license_file"):
        p = os.path.join(root, pkg["license_file"])
        if os.path.isfile(p) and p not in found:
            found.append(p)
    return found


def override_files(pkg):
    repo = (pkg.get("repository") or "").rstrip("/")
    for key in sorted(os.listdir(OVERRIDES)) if os.path.isdir(OVERRIDES) else []:
        if key.replace("__", "/") in repo:
            d = os.path.join(OVERRIDES, key)
            return [os.path.join(d, f) for f in sorted(os.listdir(d))]
    return []


def main():
    root_name = None
    pkgs = {}
    for t in TARGETS:
        meta = metadata(t)
        by_id = {p["id"]: p for p in meta["packages"]}
        root_name = by_id[meta["resolve"]["root"]]["name"]
        for i in reachable(meta):
            p = by_id[i]
            if p["name"] != root_name:
                pkgs[(p["name"], p["version"])] = p

    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    out = sys.stdout
    out.write("# Third-party licences\n\n")
    out.write(f"Generated by `tools/third_party_licenses.py` from `cargo metadata` "
              f"(all features; targets: {', '.join(TARGETS)}).\n\n")
    out.write("| Crate | Version | Licence |\n|---|---|---|\n")
    for (name, ver), p in sorted(pkgs.items()):
        out.write(f"| {name} | {ver} | {p.get('license') or 'see file'} |\n")
    out.write("\n---\n\n## Licence texts\n\n")
    texts = {}
    for (name, ver), p in sorted(pkgs.items()):
        files = (licence_files(p, ("",)) or override_files(p)) + licence_files(p, EXTRA_DIRS)
        for f in files:
            with open(f, encoding="utf-8", errors="replace") as fh:
                text = fh.read().strip()
            texts.setdefault(text, []).append(f"{name} {ver} ({os.path.basename(f)})")
        if not files:
            texts.setdefault(f"No licence file in the package; licence: {p.get('license')}; "
                             f"repository: {p.get('repository')}", []).append(f"{name} {ver}")
    for text, users in texts.items():
        out.write("### " + ", ".join(users) + "\n\n```\n" + text + "\n```\n\n")


if __name__ == "__main__":
    main()
